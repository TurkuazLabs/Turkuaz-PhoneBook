    public static String smartFieldLabel(String value) {
        return switch (value == null ? "" : value) {
            case "name" -> SMART_FIELD_NAME;
            case "phone" -> SMART_FIELD_PHONE;
            case "email" -> SMART_FIELD_EMAIL;
            case "company" -> SMART_FIELD_COMPANY;
            case "job_title" -> SMART_FIELD_JOB_TITLE;
            case "city" -> SMART_FIELD_CITY;
            case "country" -> SMART_FIELD_COUNTRY;
            case "category" -> SMART_FIELD_CATEGORY;
            case "notes" -> SMART_FIELD_NOTES;
            case "birthday" -> SMART_FIELD_BIRTHDAY;
            case "favorite" -> SMART_FIELD_FAVORITE;
            default -> value == null || value.isBlank() ? EMPTY_VALUE : value;
        };
    }

    public static String smartOperatorLabel(String value) {
        return switch (value == null ? "" : value) {
            case "contains" -> SMART_OPERATOR_CONTAINS;
            case "equals" -> SMART_OPERATOR_EQUALS;
            case "is_empty" -> SMART_OPERATOR_IS_EMPTY;
            case "not_empty" -> SMART_OPERATOR_NOT_EMPTY;
            case "true" -> SMART_OPERATOR_TRUE;
            default -> value == null || value.isBlank() ? EMPTY_VALUE : value;
        };
    }

    public static String smartRuleSummary(String field, String operator, String value) {
        String fieldLabel = smartFieldLabel(field);
        String operatorLabel = smartOperatorLabel(operator);
        if (value == null || value.isBlank()) {
            return fieldLabel + " - " + operatorLabel;
        }
        return fieldLabel + " - " + operatorLabel + " - " + value;
    }

